"""Kremer-Grest coarse-grained MD jobs via an external LAMMPS binary.

Deck generation, LAMMPS invocation, and result parsing live here so the
Host only probes binary availability. All outputs are in LJ units; they are
chain-statistics probes, never comparable to experimental seconds-scale data.
"""

from __future__ import annotations

import os
import shutil
import tempfile
from pathlib import Path
from typing import Any

SIGMA_EQUIV = 2.0 ** (1.0 / 6.0)  # LJ diameter for the excluded-volume cutoff


def resolve_lammps(explicit: str | None = None) -> str:
    """Locate a LAMMPS executable: explicit arg → PM_LAMMPS_BIN → PM_LAMMPS_HOME → PATH.

    :param explicit: caller-provided binary path (wins when it exists).
    :returns: absolute binary path.
    :raises RuntimeError: when no binary can be found.
    """
    candidates: list[str] = []
    if explicit:
        candidates.append(explicit)
    env_bin = os.environ.get("PM_LAMMPS_BIN")
    if env_bin:
        candidates.append(env_bin)
    home = os.environ.get("PM_LAMMPS_HOME")
    if home:
        suffix = ".exe" if os.name == "nt" else ""
        candidates.extend([
            str(Path(home) / "bin" / f"lmp{suffix}"),
            str(Path(home) / "bin" / f"lammps{suffix}"),
            str(Path(home) / f"lmp{suffix}"),
            home,
        ])
    for name in ("lmp", "lmp.exe", "lammps", "lammps.exe", "lmp_serial", "lmp_serial.exe", "lmp_mpi", "lmp_mpi.exe"):
        found = shutil.which(name)
        if found:
            candidates.append(found)
    for candidate in candidates:
        if candidate and os.path.isfile(candidate):
            return str(Path(candidate).resolve())
    raise RuntimeError(
        "LAMMPS binary not found; set PM_LAMMPS_BIN (executable) or PM_LAMMPS_HOME "
        "(install root), or put lmp/lammps on PATH"
    )


def build_data_file(
    chain_length: int,
    chain_count: int,
    density: float,
) -> str:
    """LAMMPS data file: chains strung along the x axis on a scaled lattice.

    :param chain_length: beads per chain N (Kremer-Grest beads).
    :param chain_count: number of chains M.
    :param density: target number density (LJ units, melt ≈ 0.85).
    :returns: the data file text.
    """
    if chain_length < 4 or chain_count < 2 or density <= 0.0:
        raise ValueError("chain_length >= 4, chain_count >= 2, density > 0 required")
    spacing = 1.2
    rows_y = max(int(round(chain_count**0.5)), 1)
    rows_z = max((chain_count + rows_y - 1) // rows_y, 1)
    bead_positions: list[tuple[int, int, int, float, float, float]] = []
    bonds: list[tuple[int, int, int]] = []
    chain = 0
    x_max = float(chain_length + 1.0)
    for iy in range(rows_y):
        for iz in range(rows_z):
            if chain >= chain_count:
                break
            y0 = spacing * iy + 0.5
            z0 = spacing * iz + 0.5
            for ix in range(chain_length):
                bead_positions.append((chain + 1, chain + 1, 1, float(ix + 1.0), y0, z0))
                if ix > 0:
                    bonds.append((chain, chain * chain_length + ix, chain * chain_length + ix + 1))
            chain += 1
    y_max = spacing * rows_y + 0.5
    z_max = spacing * rows_z + 0.5
    volume = x_max * y_max * z_max
    scale = (len(bead_positions) / (density * volume)) ** (1.0 / 3.0)
    atom_lines = []
    for molecule, _, atom_type, x, y, z in bead_positions:
        atom_lines.append(
            f"{len(atom_lines) + 1} {molecule} {atom_type} {x * scale:.6f} {y * scale:.6f} {z * scale:.6f}"
        )
    bond_lines = [
        f"{index} 1 {first} {second}" for index, (_, first, second) in enumerate(bonds, start=1)
    ]
    header = [
        "LAMMPS data file: Kremer-Grest melt (generated by pm_science.md)",
        "",
        f"{len(atom_lines)} atoms",
        f"{len(bonds)} bonds",
        "",
        "1 atom types",
        "1 bond types",
        f"0.0 {x_max * scale:.6f} xlo xhi",
        f"0.0 {y_max * scale:.6f} ylo yhi",
        f"0.0 {z_max * scale:.6f} zlo zhi",
        "",
        "Masses",
        "",
        "1 1.0",
        "",
        "Atoms # molecular",
        "",
        *atom_lines,
        "",
        "Bonds",
        "",
        *bond_lines,
        "",
    ]
    return "\n".join(header)


def build_deck(
    job: str,
    chain_length: int,
    chain_count: int,
    *,
    density: float = 0.85,
    steps: int = 20_000,
    stretch: float = 1.8,
    temperature: float = 1.0,
    final_temperature: float = 0.1,
    seed: int = 2026,
    sample_every: int = 100,
) -> str:
    """Build the LAMMPS input deck for one MD job.

    :param job: 'equilibrate' (Rg), 'deform' (uniaxial + stress anisotropy), 'cool' (PE(T) series).
    :param chain_length: beads per chain N.
    :param chain_count: number of chains M.
    :param density: starting density rescale target (LJ).
    :param steps: integration steps for the main run.
    :param stretch: final box stretch for 'deform'.
    :param temperature: equilibration/deformation temperature (LJ).
    :param final_temperature: end temperature for 'cool'.
    :param seed: velocity-create seed.
    :param sample_every: thermo/averaging stride.
    :returns: the deck text (with a rg.dat fix output for Rg jobs).
    """
    if job not in ("equilibrate", "deform", "cool"):
        raise ValueError("job must be 'equilibrate', 'deform', or 'cool'")
    data = build_data_file(chain_length, chain_count, density)
    head = [
        "units lj",
        "atom_style molecular",
        "boundary p p p",
        "atom_modify map array sort 0 0",
        "read_data DATA_PLACEHOLDER",
        "pair_style lj/cut 1.1224620483",
        "pair_coeff * * 1.0 1.0",
        "special_bonds lj 0.0 1.0 1.0",
        "bond_style fene/standard",
        "bond_coeff 1 30.0 1.5 0.0 1.5",
        "neighbor 0.4 bin",
        "neigh_modify every 1 delay 5 check yes",
        "min_style cg",
        "minimize 1.0e-4 1.0e-6 2000 20000",
        f"velocity all create {temperature:.4f} {seed} mom yes rot no dist gaussian",
        "timestep 0.005",
    ]
    if job == "equilibrate":
        lines = [
            *head,
            f"fix integr all nvt temp {temperature:.4f} {temperature:.4f} 0.5",
            "compute cid all chunk/atom molecule",
            "compute rgt all gyration/chunk cid",
            f"fix rgfile all ave/time {sample_every} 10 {sample_every * 10} c_rgt file rg.dat",
            f"thermo {sample_every * 10}",
            "thermo_style custom step temp press pe etotal",
            f"run {steps}",
            'print "PM_RESULT job=equilibrate"',
        ]
        return "\n".join(lines).replace("DATA_PLACEHOLDER", data)
    if job == "deform":
        lines = [
            *head,
            f"fix integr all nvt temp {temperature:.4f} {temperature:.4f} 0.5",
            "compute cid all chunk/atom molecule",
            "compute rgt all gyration/chunk cid",
            f"fix rgfile all ave/time {sample_every} 10 {sample_every * 10} c_rgt file rg.dat",
            f"thermo {sample_every * 10}",
            "thermo_style custom step temp pxx pyy pzz pe",
            f"fix deflect all deform 1 x final 0.0 {stretch:.4f} units lattice remap x",
            f"run {steps}",
            f'print "PM_RESULT job=deform stretch={stretch:.4f}"',
        ]
        return "\n".join(lines).replace("DATA_PLACEHOLDER", data)
    lines = [
        *head,
        f"fix integr all nvt temp {temperature:.4f} {final_temperature:.4f} 0.5",
        f"thermo {max(sample_every, 100)}",
        "thermo_style custom step temp pe",
        f"run {steps}",
        'print "PM_RESULT job=cool"',
    ]
    return "\n".join(lines).replace("DATA_PLACEHOLDER", data)


def parse_pm_results(stdout: str) -> dict[str, str]:
    """Extract key=value pairs from LAMMPS `print "PM_RESULT ..."` lines.

    :param stdout: full LAMMPS stdout.
    :returns: mapping of the last PM_RESULT line's key=value pairs.
    """
    results: dict[str, str] = {}
    for line in stdout.splitlines():
        if "PM_RESULT" in line:
            for token in line.split():
                pair = token.strip('"').split("=", 1)
                if len(pair) == 2 and pair[0] and pair[1]:
                    results[pair[0]] = pair[1]
    return results


def parse_thermo(stdout: str) -> list[dict[str, float]]:
    """Parse the last thermo table from LAMMPS stdout into row dicts.

    :param stdout: full LAMMPS stdout.
    :returns: list of rows keyed by the thermo header names.
    """
    rows: list[dict[str, float]] = []
    lines = stdout.splitlines()
    for index, line in enumerate(lines):
        if line.strip().startswith("Step ") and index + 1 < len(lines):
            header = line.split()
            block: list[dict[str, float]] = []
            for candidate in lines[index + 1:]:
                cells = candidate.split()
                if len(cells) == len(header) and all(_is_number(cell) for cell in cells):
                    block.append({name: float(cell) for name, cell in zip(header, cells)})
                elif block:
                    break
            if block:
                rows = block
    return rows


def _is_number(token: str) -> bool:
    try:
        float(token)
        return True
    except ValueError:
        return False


def parse_rg_file(text: str) -> float:
    """Average the per-chunk Rg values from a fix ave/time rg.dat file.

    File rows are ``timestep nchunks v1 … vN`` (comments start with ``#``), so
    the first two numeric columns are metadata and the rest are Rg samples.
    :param text: file content.
    :returns: mean Rg across chunks and samples.
    """
    values: list[float] = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        cells = [token for token in stripped.split() if _is_number(token)]
        if len(cells) >= 3:
            values.extend(float(token) for token in cells[2:])
    if not values:
        raise ValueError("rg.dat contains no numeric value rows")
    return sum(values) / len(values)


def run_md(
    args: dict[str, Any],
    *,
    explicit_bin: str | None = None,
    keep_workdir: bool = False,
) -> dict[str, Any]:
    """Run one MD job end to end: locate LAMMPS → write files → run → parse.

    :param args: {job, chainLength, chainCount, density?, steps?, stretch?, temperature?, finalTemperature?, seed?}
    :param explicit_bin: explicit binary path override.
    :param keep_workdir: keep the temporary working directory (diagnostics).
    :returns: {status, job, observables, thermo, workdir?, definitions}
    """
    import subprocess

    job = str(args.get("job", "equilibrate"))
    chain_length = int(args.get("chainLength", 20))
    chain_count = int(args.get("chainCount", 64))
    deck = build_deck(
        job,
        chain_length,
        chain_count,
        density=float(args.get("density", 0.85)),
        steps=int(args.get("steps", 20_000)),
        stretch=float(args.get("stretch", 1.8)),
        temperature=float(args.get("temperature", 1.0)),
        final_temperature=float(args.get("finalTemperature", 0.1)),
        seed=int(args.get("seed", 2026)),
    )
    binary = resolve_lammps(explicit_bin)
    workdir = Path(tempfile.mkdtemp(prefix="pm-md-"))
    (workdir / "in.pmmd").write_text(deck, encoding="utf-8")
    argv = [binary, "-in", "in.pmmd", "-log", "none", "-screen", "none"]
    try:
        completed = subprocess.run(
            argv,
            cwd=workdir,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=float(args.get("timeoutS", 600)),
            check=False,
        )
        stdout = completed.stdout or ""
        if completed.returncode != 0:
            raise RuntimeError(f"LAMMPS exited {completed.returncode}: {(completed.stderr or stdout)[-500:]}")
        observables: dict[str, Any] = dict(parse_pm_results(stdout))
        if job in ("equilibrate", "deform"):
            rg_path = workdir / "rg.dat"
            if rg_path.exists():
                observables["meanRg"] = parse_rg_file(rg_path.read_text(encoding="utf-8"))
        if job == "deform":
            rows = parse_thermo(stdout)
            if rows:
                last = rows[-1]
                lowered = {key.lower(): value for key, value in last.items()}
                pxx = lowered.get("pxx", 0.0)
                pyy = lowered.get("pyy", 0.0)
                pzz = lowered.get("pzz", 0.0)
                total = pxx + pyy + pzz
                observables["stressAnisotropy"] = (pxx - 0.5 * (pyy + pzz)) / total if total != 0 else 0.0
        if job == "cool":
            rows = parse_thermo(stdout)
            series = [{"temperature": row.get("Temp", 0.0), "potentialEnergy": row.get("PotEng", 0.0)} for row in rows]
            observables["peSeries"] = series
            observables["tgEstimate"] = _tg_from_pe_series(series)
        return {
            "status": "OK",
            "job": job,
            "chainLength": chain_length,
            "chainCount": chain_count,
            "observables": observables,
            "thermoTail": parse_thermo(stdout)[-3:],
            **({"workdir": str(workdir)} if keep_workdir else {}),
            "definitions": {
                "units": "reduced Lennard-Jones units; times are τ, NOT seconds — do not compare to experimental relaxation",
                "meanRg": "mean per-chain radius of gyration (LJ σ)",
                "stressAnisotropy": "(Pxx − (Pyy+Pzz)/2)/(Pxx+Pyy+Pzz) under uniaxial box deformation; a stress proxy, not a chain P2 order parameter",
                "tgEstimate": "two-segment PE(T) fit kink; coarse-grained LJ-unit Tg, not comparable to experimental Tg",
            },
        }
    finally:
        if not keep_workdir:
            shutil.rmtree(workdir, ignore_errors=True)


def _tg_from_pe_series(series: list[dict[str, float]]) -> float | None:
    """Two-segment least-squares kink fit over the PE(T) series."""
    points = [(row["temperature"], row["potentialEnergy"]) for row in series if row.get("temperature")]
    if len(points) < 6:
        return None
    points.sort()
    temps = [t for t, _ in points]
    energies = [e for _, e in points]
    best_error = float("inf")
    best_kink = None
    for split in range(2, len(points) - 2):
        left_t, left_e = temps[:split], energies[:split]
        right_t, right_e = temps[split:], energies[split:]
        slope_l, intercept_l = _fit_line(left_t, left_e)
        slope_r, intercept_r = _fit_line(right_t, right_e)
        if slope_l is None or slope_r is None:
            continue
        error = _sse(left_t, left_e, slope_l, intercept_l) + _sse(right_t, right_e, slope_r, intercept_r)
        if error < best_error:
            best_error = error
            kink_x = (intercept_r - intercept_l) / (slope_l - slope_r)
            best_kink = kink_x if min(left_t) <= kink_x <= max(right_t) else None
    return best_kink


def _fit_line(xs: list[float], ys: list[float]) -> tuple[float | None, float | None]:
    n = len(xs)
    if n < 2 or max(xs) - min(xs) < 1e-9:
        return None, None
    mean_x = sum(xs) / n
    mean_y = sum(ys) / n
    denom = sum((x - mean_x) ** 2 for x in xs)
    if denom < 1e-12:
        return None, None
    slope = sum((x - mean_x) * (y - mean_y) for x, y in zip(xs, ys)) / denom
    return slope, mean_y - slope * mean_x


def _sse(xs: list[float], ys: list[float], slope: float, intercept: float) -> float:
    return sum((y - (slope * x + intercept)) ** 2 for x, y in zip(xs, ys))
